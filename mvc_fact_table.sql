SELECT VEHICLE_TYPE_CODE_1,
ROUND(((COUNT(*)*1.0)/(SELECT COUNT(*) FROM MVC_FACT))*100,2) AS percentage,
COUNT(*) as '# of occurences',
SUM(ROUND(((COUNT(*)*1.0)/(SELECT COUNT(*) FROM MVC_FACT))*100,2)) over (order by ((COUNT(*)*1.0)/(SELECT COUNT(*) FROM MVC_FACT))*100 DESC) as running_total,
ROW_NUMBER() over (order by Count(*) desc) as rn
FROM MVC_FACT
GROUP BY VEHICLE_TYPE_CODE_1;

with cte as (
SELECT VEHICLE_TYPE_CODE_1,
ROUND(((COUNT(*)*1.0)/(SELECT COUNT(*) FROM MVC_FACT))*100,2) AS percentage,
COUNT(*) as '# of occurences',
SUM(ROUND(((COUNT(*)*1.0)/(SELECT COUNT(*) FROM MVC_FACT))*100,2)) over (order by ((COUNT(*)*1.0)/(SELECT COUNT(*) FROM MVC_FACT))*100 DESC) as running_total,
ROW_NUMBER() over (order by Count(*) desc) as rn
FROM MVC_FACT
GROUP BY VEHICLE_TYPE_CODE_1
)
SELECT *,
CASE WHEN running_total <= 95.5 THEN 'TOP 95.5%' ELSE 'OTHER' END AS 'SUB GROUP'
FROM CTE;

