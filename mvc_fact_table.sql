drop table mvc_fact;
CREATE TABLE MVC_FACT(
	COLLISION_ID VARCHAR(7) PRIMARY KEY,
	CRASH_DATE DATE NOT NULL,
	CRASH_TIME TIME(7) NOT NULL,
	BOROUGH VARCHAR(13) NOT NULL,
	ZIPCODE CHAR(5)  NOT NULL,
	LATITUDE DECIMAL(8,6) NULL,
	LONGITUDE DECIMAL(9,6) NULL,
	LOCATION VARCHAR(50) NULL, -- TRIGGER UPDATE: LAT + LONG
	PERSONS_INJURED INT DEFAULT 0,
	PERSONS_KILLED INT DEFAULT 0,
	PEDESTRIANS_INJURED INT DEFAULT 0,
	PEDESTRIANS_KILLED INT DEFAULT 0,
	CYCLIST_INJURED INT DEFAULT 0,
	CYCLIST_KILLED INT DEFAULT 0,
	MOTORIST_INJURED INT DEFAULT 0,
	MOTORIST_KILLED INT DEFAULT 0,
	CONTRIBUTING_FACTOR VARCHAR(max) DEFAULT 'UNSPECIFIED',
	VEHICLE_TYPE_CODE_1 VARCHAR(50) DEFAULT 'UNSPECIFIED',
	CONSTRAINT CK_BOROUGH CHECK (BOROUGH IN ('MANHATTAN','BROOKLYN','QUEENS','STATEN ISLAND','BRONX','UNSPECIFIED')),
);

WITH MVC_TC AS (
	SELECT 
		raw_collisions.COLLISION_ID,
		raw_collisions.CRASH_DATE,
		raw_collisions.CRASH_TIME,
		CASE WHEN raw_collisions.BOROUGH IS NULL THEN 'UNSPECIFIED' ELSE BOROUGH END AS BOROUGH,
		CASE WHEN raw_collisions.ZIP_CODE IS NULL THEN '00000' ELSE ZIP_CODE END AS ZIP_CODE, 
		CASE WHEN raw_collisions.LATITUDE IS NULL THEN 0.0 ELSE raw_collisions.LATITUDE END AS LATITUDE,
		CASE WHEN raw_collisions.LONGITUDE IS NULL THEN 0.0 ELSE raw_collisions.LONGITUDE END AS LONGITUDE,
		CASE WHEN raw_collisions.LOCATION IS NULL THEN 'UNSPECIFIED' ELSE raw_collisions.LOCATION END AS LOCATION,
		raw_collisions.NUMBER_OF_PERSONS_INJURED,
		raw_collisions.NUMBER_OF_PERSONS_KILLED,
		raw_collisions.NUMBER_OF_PEDESTRIANS_INJURED,
		raw_collisions.NUMBER_OF_PEDESTRIANS_KILLED,
		raw_collisions.NUMBER_OF_CYCLIST_INJURED,
		raw_collisions.NUMBER_OF_CYCLIST_KILLED,
		raw_collisions.NUMBER_OF_MOTORIST_INJURED,
		raw_collisions.NUMBER_OF_MOTORIST_KILLED,
		raw_collisions.CONTRIBUTING_FACTOR_VEHICLE_1,
		raw_collisions.VEHICLE_TYPE_CODE_1
	FROM raw_collisions
	)
