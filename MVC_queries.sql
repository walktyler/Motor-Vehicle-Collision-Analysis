--Collision Volume
--Total collisions
SELECT COUNT(*) FROM MVC_FACT;
--Human Impact
--Persons Injured
SELECT
SUM(PERSONS_INJURED) 'Total Persons Injured',
SUM(PEDESTRIANS_INJURED) 'Total Pedestrians Injured',
SUM(CYCLIST_INJURED) 'Total Cyclist Injured',
SUM(MOTORIST_INJURED) 'Total Motorist Injured'
FROM MVC_FACT;
--Persons Killed
SELECT
SUM(PERSONS_KILLED) 'Total Persons Killed',
SUM(PEDESTRIANS_KILLED) 'Total Pedestrians Killed',
SUM(CYCLIST_KILLED) 'Total Cyclist Killed',
SUM(MOTORIST_KILLED) 'Total Motorist Killed'
FROM MVC_FACT;

--Fatal Collision Rate
SELECT SUM(CASE WHEN PERSONS_KILLED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) AS 'Fatal Collision Rate' FROM MVC_FACT
--Fatal Collision per 100 collisions
SELECT
((SELECT SUM(PERSONS_KILLED*1.0 ) FROM MVC_FACT)/ COUNT(*))*100 AS 'Fatal Collision Rate' FROM MVC_FACT; 

--Severity Metrics
--Average Injured per collision
SELECT SUM(CASE WHEN PERSONS_INJURED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) AS 'Average Injured per Collision' FROM MVC_FACT
--Average Killed per collision
SELECT AVG(PERSONS_KILLED*1.0) AS 'Average Killed per Collision' FROM MVC_FACT;

-- MOST PEOPLE KILLED BY YEAR
SELECT YEAR(CRASH_DATE) 'YEAR',
SUM(PERSONS_KILLED) 'TOTAL KILLED',
DENSE_RANK() OVER (ORDER BY SUM(PERSONS_KILLED) DESC) AS 'RANK'
FROM MVC_FACT
GROUP BY YEAR(CRASH_DATE) 
ORDER BY SUM(PERSONS_KILLED) DESC

select top 100 PERSONS_INJURED, PEDESTRIANS_INJURED, CYCLIST_INJURED, MOTORIST_INJURED from MVC_FACT
where PERSONS_INJURED > 1;

-- Total Fatalities per year

SELECT YEAR(CRASH_DATE) 'Year',
SUM(PERSONS_KILLED) 'Total Fatalities per year',
SUM(PERSONS_INJURED)  FROM MVC_FACT
GROUP BY YEAR(CRASH_DATE)
ORDER BY YEAR(CRASH_DATE);

-- Fatal Collision Rate by Borough
SELECT 
BOROUGH,
SUM(CASE WHEN PERSONS_KILLED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) 'Fatal Collision Rate'
FROM MVC_FACT
WHERE BOROUGH != 'UNSPECIFIED'
GROUP BY BOROUGH
order by 'Fatal Collision Rate' DESC;

-- Fatal Collision Rate by Year
SELECT 
YEAR(CRASH_DATE) 'Year',
COUNT(*) '# of Collisions',
SUM(PERSONS_KILLED) '# of People Killed',
SUM(CASE WHEN PERSONS_KILLED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) 'Fatal Collision Rate'
FROM MVC_FACT
GROUP BY YEAR(CRASH_DATE) 
order by YEAR(CRASH_DATE);


-- Fatal Collision Rate at Night, compared to the Day
SELECT
CASE WHEN DATEPART(HOUR,CRASH_TIME) BETWEEN 6 AND 18 THEN 'Day' ELSE 'Night' END as Time_of_Day,
SUM(CASE WHEN PERSONS_KILLED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) Fatal_Collision_Rate
FROM MVC_FACT
GROUP BY 
CASE WHEN DATEPART(HOUR,CRASH_TIME) BETWEEN 6 AND 18 THEN 'Day' ELSE 'Night'
END;

--weekends vs weekdays

SELECT
	COUNT(*) AS TOTAL_COLLISIONS,
	SUM(CASE WHEN PERSONS_KILLED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) Fatal_Collision_Rate,
	CASE WHEN DATENAME(W,CRASH_DATE) IN ('Saturday', 'Sunday') THEN 'WEEKEND' ELSE 'WEEKDAY' END AS WD
FROM MVC_FACT
	GROUP BY CASE WHEN DATENAME(W,CRASH_DATE) IN ('Saturday', 'Sunday') THEN 'WEEKEND' ELSE 'WEEKDAY' END;


