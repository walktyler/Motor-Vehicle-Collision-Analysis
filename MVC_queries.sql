-- GROWTH RATE YTD
WITH CTE AS(
	SELECT 
		YEAR(CRASH_DATE) AS YEAR,
		COUNT(*) AS Total_Collisions,
		lag(COUNT(*)*1.0 ) OVER (ORDER BY YEAR(CRASH_DATE)) AS PREV_YEAR_COLLISIONS
	FROM raw_collisions
	GROUP BY YEAR(CRASH_DATE)
)
SELECT 
	YEAR,
	TOTAL_COLLISIONS,
	TOTAL_COLLISIONS - PREV_YEAR_COLLISIONS AS GROWTH,
	ROUND((TOTAL_COLLISIONS - PREV_YEAR_COLLISIONS)*100.0/PREV_YEAR_COLLISIONS,2) AS GROWTH_RATE
	FROM CTE

-- Are fatalities going up or down year over year?
--Need: Fatalities per year

WITH CTE AS
(
	SELECT
		YEAR(CRASH_DATE) AS YEAR,
		SUM(PERSONS_KILLED) AS TOTAL_KILLED_PER_YEAR,
		LAG(SUM(PERSONS_KILLED)*1.0) OVER (ORDER BY YEAR(CRASH_DATE)) AS PREV_YEAR_KILLED
	FROM MVC_FACT
		GROUP BY YEAR(CRASH_DATE)
)
SELECT
	YEAR,
	TOTAL_KILLED_PER_YEAR,
	ROUND(((TOTAL_KILLED_PER_YEAR - PREV_YEAR_KILLED)/PREV_YEAR_KILLED)*100,2) AS GROWTH_RATE
FROM CTE
WHERE YEAR != 2026;

--An assessment of pedestrian, cyclist, and motorist injury and fatality exposure.

SELECT 
	BOROUGH,
	SUM(CASE WHEN PEDESTRIANS_INJURED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) AS PEDESTRIAN_INJURY_RATE,
	SUM(CASE WHEN PEDESTRIANS_KILLED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) AS PEDESTRIAN_FATALITY_RATE,
	SUM(CASE WHEN CYCLIST_INJURED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) AS CYCLIST_INJURY_RATE,
	SUM(CASE WHEN CYCLIST_KILLED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) AS CYCLIST_FATALITY_RATE,
	SUM(CASE WHEN MOTORIST_INJURED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) AS MOTORIST_INJURY_RATE,
	SUM(CASE WHEN MOTORIST_KILLED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) AS MOTORIST_FATALITY_RATE
FROM MVC_FACT
	WHERE BOROUGH != 'UNSPECIFIED'
	GROUP BY BOROUGH
	
	
--Injury Percentage
SELECT 
	SUM(PEDESTRIANS_INJURED*1.0)/SUM(PERSONS_INJURED),
	SUM(CYCLIST_INJURED*1.0)/SUM(PERSONS_INJURED),
	SUM(MOTORIST_INJURED*1.0)/SUM(PERSONS_INJURED)
FROM MVC_FACT

--Where are pedestrians most at risk
SELECT 
	BOROUGH,
	SUM(CASE WHEN PEDESTRIANS_INJURED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) AS PEDESTRIAN_INJURY_RATE,
	SUM(CASE WHEN PEDESTRIANS_KILLED > 0 THEN 1.0 ELSE 0 END) / COUNT(*) AS PEDESTRIAN_FATALITY_RATE
FROM MVC_FACT
	WHERE BOROUGH != 'UNSPECIFIED'
	GROUP BY BOROUGH
	order by PEDESTRIAN_INJURY_RATE desc, PEDESTRIAN_FATALITY_RATE desc 

--Top 10 dangerous zipcodes
SELECT
	ZIPCODE,
	COUNT(*) AS TOTAL_COLLISIONS,
	SUM(CASE WHEN PERSONS_INJURED > 0 THEN 1.0 ELSE 0 END)/COUNT(*) AS INJURY_RATE
FROM MVC_FACT
	WHERE ZIPCODE != 0
	GROUP BY ZIPCODE
	ORDER BY TOTAL_COLLISIONS DESC, INJURY_RATE DESC;

